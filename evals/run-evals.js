/*
 * Scores the demo's keyword matcher on the eval cases, before and after tuning.
 *   node evals/run-evals.js            (from the repo root; needs only Node)
 *
 * "Before" is a frozen copy of the rules as they were before tuning (evals/v1). "After" is the live demo/matcher.js.
 * This scores the stand-in matcher, not a language model. A real model would plug in behind the same function:
 *   mapObservation(note, roster, framework, photoTags)
 * Writes evals/RESULTS.md. No timestamps, so a re-run only changes the file when a score changes.
 */
const fs = require("fs"), path = require("path");
const DATA = require("../demo/data.js");
const { loadCases, scoreCase } = require("./score.js");

const VERSIONS = [
  { key: "before", matcher: require("./v1/matcher.js"), framework: require("./v1/framework.js") },
  { key: "after", matcher: require("../demo/matcher.js"), framework: require("../demo/framework.js") }
];

function describe(res) {
  if (res.status === "needs_attention") return "flagged as sensitive (" + res.reason.replace("Mentions ", "") + ")";
  if (res.status === "no_match") return "no suggestion";
  return "suggests " + res.suggestions.map((s) => s.goalId + " " + s.confidence).join(", ");
}

const cases = loadCases();
const out = {};
VERSIONS.forEach((v) => {
  out[v.key] = cases.map((c) => {
    const res = v.matcher.mapObservation(c.note, DATA.roster, v.framework, c.photoTags || []);
    return { c, res, ...scoreCase(c, res), text: describe(res) };
  });
});

function metrics(rows) {
  const flagCases = rows.filter((r) => r.c.area.startsWith("Safety"));
  const lookalikes = rows.filter((r) => r.c.area.startsWith("Look-alike"));
  const high = rows.flatMap((r) => (r.res.suggestions || []).filter((s) => s.confidence === "High").map((s) => ({ s, r })));
  const wrongHigh = high.filter(({ s, r }) => !(r.c.expect.accept || []).includes(s.goalId) || r.c.expect.noHigh);
  return {
    cases: rows.length, passed: rows.filter((r) => r.pass).length,
    safetyCaught: flagCases.filter((r) => r.res.status === "needs_attention").length, safetyTotal: flagCases.length,
    falseAlarms: lookalikes.filter((r) => r.res.status === "needs_attention").length, lookalikeTotal: lookalikes.length,
    highTotal: high.length, highWrong: wrongHigh.length,
    childrenRight: rows.filter((r) => r.checks.children).length
  };
}
const sets = [...new Set(cases.map((c) => c.set))];
const pick = (key, set) => out[key].filter((r) => r.c.set === set);

// ---- console
const pad = (s, n) => String(s).padEnd(n);
console.log(pad("case", 6) + pad("set", 10) + pad("before", 8) + pad("after", 8) + "area");
cases.forEach((c, i) => console.log(pad(c.id, 6) + pad(c.set, 10) + pad(out.before[i].pass ? "pass" : "FAIL", 8) + pad(out.after[i].pass ? "pass" : "FAIL", 8) + c.area));
console.log("");
const summary = [];
sets.forEach((set) => {
  const b = metrics(pick("before", set)), a = metrics(pick("after", set));
  summary.push({ set, b, a });
  console.log(set + ": cases passed " + b.passed + "/" + b.cases + " before, " + a.passed + "/" + a.cases + " after");
});
const all = { b: metrics(out.before), a: metrics(out.after) };
console.log("all: safety notes caught " + all.b.safetyCaught + "/" + all.b.safetyTotal + " before, " + all.a.safetyCaught + "/" + all.a.safetyTotal + " after");
console.log("all: look-alikes wrongly flagged " + all.b.falseAlarms + "/" + all.b.lookalikeTotal + " before, " + all.a.falseAlarms + "/" + all.a.lookalikeTotal + " after");
console.log("all: High suggestions that were wrong " + all.b.highWrong + "/" + all.b.highTotal + " before, " + all.a.highWrong + "/" + all.a.highTotal + " after");

// ---- RESULTS.md
const mark = (r) => (r.pass ? "pass" : "fail");
let md = "# Eval results\n\nGenerated by `node evals/run-evals.js`. Do not edit by hand. Read [`README.md`](README.md) first for what these numbers do and do not mean.\n\n";
md += "## Scores\n\n| Set | Cases passed before | Cases passed after |\n|---|---|---|\n";
summary.forEach((s) => { md += "| " + (s.set === "tuning" ? "Tuning set (used to improve the rules)" : "Held-out set (never used to change a rule)") + " | " + s.b.passed + " of " + s.b.cases + " | " + s.a.passed + " of " + s.a.cases + " |\n"; });
md += "\n| Measure (all cases) | Before | After |\n|---|---|---|\n";
md += "| Injury, illness or safeguarding notes caught | " + all.b.safetyCaught + " of " + all.b.safetyTotal + " | " + all.a.safetyCaught + " of " + all.a.safetyTotal + " |\n";
md += "| Harmless look-alike notes wrongly flagged (lower is better) | " + all.b.falseAlarms + " of " + all.b.lookalikeTotal + " | " + all.a.falseAlarms + " of " + all.a.lookalikeTotal + " |\n";
md += "| High-confidence suggestions that were wrong (lower is better) | " + all.b.highWrong + " of " + all.b.highTotal + " | " + all.a.highWrong + " of " + all.a.highTotal + " |\n";
md += "| Cases where the children named were found exactly | " + all.b.childrenRight + " of " + all.b.cases + " | " + all.a.childrenRight + " of " + all.a.cases + " |\n";
md += "\n## Every case\n\n| ID | Set | Area | Note | Before | After | What the rules did after tuning |\n|---|---|---|---|---|---|---|\n";
cases.forEach((c, i) => { md += "| " + c.id + " | " + c.set + " | " + c.area + " | " + c.note.replace(/\|/g, "/") + " | " + mark(out.before[i]) + " | " + mark(out.after[i]) + " | " + out.after[i].text + " |\n"; });
md += "\n## What the rules did before tuning, for the cases that failed\n\n| ID | What happened |\n|---|---|\n";
cases.forEach((c, i) => { if (!out.before[i].pass) md += "| " + c.id + " | " + out.before[i].text + " |\n"; });
fs.writeFileSync(path.join(__dirname, "RESULTS.md"), md);
console.log("\nwrote evals/RESULTS.md");
